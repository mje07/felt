// Generates lib/src/bots/preflop_table.g.dart.
// Run: dart run tool/gen_preflop.dart [samplesPerHand]
import 'dart:io';
import 'dart:math';

import 'package:poker_engine/src/card.dart';
import 'package:poker_engine/src/evaluator.dart';

void main(List<String> args) {
  final samples = args.isEmpty ? 60000 : int.parse(args.first);
  final rng = Random(42);
  final equity = List<double>.filled(169, 0);
  final combos = List<int>.filled(169, 0);
  for (var row = 0; row < 13; row++) {
    for (var col = 0; col < 13; col++) {
      final idx = row * 13 + col;
      late int a, b;
      if (row == col) {
        a = makeCard(row, 0);
        b = makeCard(row, 1);
        combos[idx] = 6;
      } else if (row > col) {
        a = makeCard(row, 0);
        b = makeCard(col, 0);
        combos[idx] = 4;
      } else {
        a = makeCard(col, 0);
        b = makeCard(row, 1);
        combos[idx] = 12;
      }
      equity[idx] = _equity(a, b, samples, rng);
    }
  }
  final order = List<int>.generate(169, (i) => i)
    ..sort((x, y) => equity[y].compareTo(equity[x]));
  final percentile = List<double>.filled(169, 0);
  var cum = 0;
  for (final i in order) {
    cum += combos[i];
    percentile[i] = cum / 1326;
  }
  String fmt(List<double> l) =>
      l.map((v) => v.toStringAsFixed(4)).join(', ');
  File('lib/src/bots/preflop_table.g.dart').writeAsStringSync('''
// GENERATED by tool/gen_preflop.dart ($samples samples/hand). Do not edit.
// 13x13 grid; see startingHandIndex().

const List<double> preflopEquityTable = [${fmt(equity)}];

const List<double> preflopPercentileTable = [${fmt(percentile)}];
''');
  stdout.writeln('Top 10: ${order.take(10).map((i) => '${_name(i)} ${(equity[i] * 100).toStringAsFixed(1)}%').join(', ')}');
}

String _name(int index) {
  final row = index ~/ 13, col = index % 13;
  if (row == col) return '${rankChars[row]}${rankChars[row]}';
  if (row > col) return '${rankChars[row]}${rankChars[col]}s';
  return '${rankChars[col]}${rankChars[row]}o';
}

double _equity(int a, int b, int n, Random rng) {
  final hero = List<int>.filled(7, 0), opp = List<int>.filled(7, 0);
  var share = 0.0;
  for (var i = 0; i < n; i++) {
    var used = (1 << a) | (1 << b);
    int draw() {
      while (true) {
        final c = rng.nextInt(52);
        if ((used >> c) & 1 == 0) {
          used |= 1 << c;
          return c;
        }
      }
    }

    hero[0] = a;
    hero[1] = b;
    opp[0] = draw();
    opp[1] = draw();
    for (var k = 2; k < 7; k++) {
      hero[k] = opp[k] = draw();
    }
    final h = evaluate(hero), o = evaluate(opp);
    share += h > o ? 1 : (h == o ? 0.5 : 0);
  }
  return share / n;
}
